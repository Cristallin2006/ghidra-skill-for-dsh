def _import_frida():
    try:
        import frida
        return frida
    except ImportError:
        emit({"ok": False, "gate": "frida-missing", "error": VENV_HINT})
        sys.exit(2)


def _get_device(frida, which: str):
    if which == "usb":
        try:
            return frida.get_usb_device(timeout=5)
        except Exception as e:
            emit({"ok": False, "gate": "usb-device-missing", "error": str(e)})
            sys.exit(2)
    return frida.get_local_device()


def run_one(device, js: str, args, spawn_argv: list[str] | None) -> dict:
    """Attach/spawn one target, load script, wait detached/timeout, collect."""
    frida = _import_frida()
    result: dict = {"hits": 0, "messages": [], "installed": None,
                    "selfcheck": None, "js_errors": []}
    detached = threading.Event()

    win_spawn: WinSpawn | None = None
    session = None
    try:
        if spawn_argv is not None:
            if IS_WINDOWS:
                win_spawn = _spawn_suspended_win32(spawn_argv[0], spawn_argv[1:])
                pid = win_spawn.pid
            else:
                pid = device.spawn(spawn_argv[0], argv=spawn_argv[1:], stdio="inherit")
                result["warning"] = ("非 Windows 宿主：stdout 未捕获（inherit 上屏），"
                                     "--pattern 匹配不可用")
            session = device.attach(pid)
            result["pid"] = pid
        else:
            target = args.pid if args.pid is not None else args.attach
            try:
                session = device.attach(target)
            except Exception as e:
                emit({"ok": False, "gate": "attach-failed", "target": str(target),
                      "error": str(e)})
                sys.exit(2)
            result["pid"] = session.pid

        script = session.create_script(js)

        def on_message(message, data):
            if message.get("type") == "error":
                result["js_errors"].append(message.get("description", str(message)))
                return
            payload = message.get("payload") or {}
            if not isinstance(payload, dict):
                return
            kind = payload.get("t")
            if kind == "hit":
                result["hits"] += 1
            elif kind == "installed":
                result["installed"] = payload
            elif kind == "selfcheck":
                result["selfcheck"] = payload
            else:
                result["messages"].append(payload)

        def on_detached(reason, *rest):
            result["detach_reason"] = reason
            detached.set()

        script.on("message", on_message)
        session.on("detached", on_detached)
        script.load()

        if win_spawn is not None:
            win_spawn.resume()
        elif spawn_argv is not None:
            device.resume(pid)

        detached.wait(args.timeout)
        if not detached.is_set():
            result["timeout"] = True
            if spawn_argv is not None:
                try:
                    device.kill(result["pid"])
                except Exception:
                    pass
        # 给 in-flight message 一点时间
        _time.sleep(0.3)

        if win_spawn is not None:
            code = win_spawn.wait(3)
            result["exit_code"] = code
            out, err = win_spawn.drain()
            result["stdout"] = out
            if err.strip():
                result["stderr"] = err
            win_spawn.close()
    except SystemExit:
        raise
    except Exception as e:
        result["fatal"] = f"{type(e).__name__}: {e}"
    finally:
        if session is not None:
            try:
                session.detach()
            except Exception:
                pass
    return result


def check_pattern(result: dict, pattern: re.Pattern | None) -> str | None:
    if pattern is None:
        return None
    m = pattern.search(result.get("stdout") or "")
    return m.group(0) if m else None


