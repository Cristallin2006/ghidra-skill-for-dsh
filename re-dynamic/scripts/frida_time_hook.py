_JS_FIND_EXPORT = r"""
  function findExport(name, moduleName) {
    if (moduleName) {
      if (typeof Module.getExportByName === 'function') {
        try { var p = Module.getExportByName(moduleName, name); if (p) return p; } catch (e) {}
      }
      try { return Module.findExportByName(moduleName, name); } catch (e) { return null; }
    }
    if (typeof Module.getGlobalExportByName === 'function') {          // frida 17
      try { var g = Module.getGlobalExportByName(name); if (g) return g; } catch (e) {}
    }
    if (typeof Module.findGlobalExportByName === 'function') {         // frida 16
      try { var g2 = Module.findGlobalExportByName(name); if (g2) return g2; } catch (e) {}
    }
    try { return Module.findExportByName(null, name); } catch (e) { return null; }
  }
"""

WIN_JS = r"""// frida_time_hook [win] generated by re-dynamic/scripts/frida_time_hook.py
// pins GetSystemTimeAsFileTime / GetSystemTimePreciseAsFileTime to unix __UNIX__
'use strict';
(function () {
  var UNIX = __UNIX__;
  var FT_LO = __FT_LO__;
  var FT_HI = __FT_HI__;
""" + _JS_FIND_EXPORT + r"""
  var hooked = [];
  var seen = {};
  function hookFiletime(name) {
    var addrs = [];
    ['kernelbase.dll', 'kernel32.dll'].forEach(function (m) {
      var a = findExport(name, m);
      if (a && !seen[a.toString()]) { seen[a.toString()] = true; addrs.push(a); }
    });
    if (addrs.length === 0) {
      var g = findExport(name, null);
      if (g && !seen[g.toString()]) { seen[g.toString()] = true; addrs.push(g); }
    }
    addrs.forEach(function (addr) {
      Interceptor.attach(addr, {
        onEnter: function (args) { this.buf = args[0]; },
        onLeave: function () {
          if (this.buf && !this.buf.isNull()) {
            this.buf.writeU32(FT_LO >>> 0);
            this.buf.add(4).writeU32(FT_HI >>> 0);
          }
          send({ t: 'hit', api: name, unix: UNIX });
        }
      });
      hooked.push(name + '@' + addr);
    });
    return addrs.length ? addrs[0] : null;
  }

  var primary = hookFiletime('GetSystemTimeAsFileTime');
  hookFiletime('GetSystemTimePreciseAsFileTime');
  if (hooked.length === 0) { send({ t: 'error', error: 'no filetime api resolvable' }); return; }
  send({ t: 'installed', source: 'win', hooked: hooked, unix: UNIX });

  if (__SELFCHECK__) {
    try {
      var f = new NativeFunction(primary, 'void', ['pointer']);
      var buf = Memory.alloc(8);
      f(buf);
      var lo = buf.readU32();
      var hi = buf.add(4).readU32();
      send({ t: 'selfcheck', api: 'GetSystemTimeAsFileTime',
             observed_lo: lo, observed_hi: hi,
             expected_lo: FT_LO >>> 0, expected_hi: FT_HI >>> 0,
             ok: (lo === (FT_LO >>> 0)) && (hi === (FT_HI >>> 0)) });
    } catch (e) { send({ t: 'selfcheck', ok: false, error: '' + e }); }
  }
})();
"""

LINUX_JS = r"""// frida_time_hook [linux] generated by re-dynamic/scripts/frida_time_hook.py
// pins time/gettimeofday/clock_gettime to unix __UNIX__
'use strict';
(function () {
  var UNIX = __UNIX__;
  var ALL_CLOCKS = __ALL_CLOCKS__;
  var PS = Process.pointerSize;
""" + _JS_FIND_EXPORT + r"""
  function writeLong(buf, v) { if (PS === 8) buf.writeS64(v); else buf.writeS32(v); }
  var hooked = [];

  var pTime = findExport('time', null);
  if (pTime) {
    Interceptor.attach(pTime, {
      onEnter: function (args) { this.tloc = args[0]; },
      onLeave: function (retval) {
        retval.replace(ptr(UNIX));
        if (this.tloc && !this.tloc.isNull()) writeLong(this.tloc, UNIX);
        send({ t: 'hit', api: 'time', unix: UNIX });
      }
    });
    hooked.push('time');
  }
  var pGtod = findExport('gettimeofday', null);
  if (pGtod) {
    Interceptor.attach(pGtod, {
      onEnter: function (args) { this.tv = args[0]; },
      onLeave: function () {
        if (this.tv && !this.tv.isNull()) {
          writeLong(this.tv, UNIX);
          writeLong(this.tv.add(PS), 0);
        }
        send({ t: 'hit', api: 'gettimeofday', unix: UNIX });
      }
    });
    hooked.push('gettimeofday');
  }
  var pCgt = findExport('clock_gettime', null);
  if (pCgt) {
    Interceptor.attach(pCgt, {
      onEnter: function (args) { this.clk = args[0].toInt32(); this.ts = args[1]; },
      onLeave: function () {
        if (!ALL_CLOCKS && this.clk !== 0) return;  // 只钉 CLOCK_REALTIME
        if (this.ts && !this.ts.isNull()) {
          writeLong(this.ts, UNIX);
          writeLong(this.ts.add(PS), 0);
        }
        send({ t: 'hit', api: 'clock_gettime', unix: UNIX });
      }
    });
    hooked.push('clock_gettime');
  }
  if (hooked.length === 0) { send({ t: 'error', error: 'no libc time api resolvable' }); return; }
  send({ t: 'installed', source: 'linux', hooked: hooked, unix: UNIX });

  if (__SELFCHECK__ && pTime) {
    try {
      var tf = new NativeFunction(pTime, 'long', ['pointer']);
      var observed = tf(NULL);
      send({ t: 'selfcheck', api: 'time', observed_unix: observed,
             expected_unix: UNIX, ok: observed === UNIX });
    } catch (e) { send({ t: 'selfcheck', ok: false, error: '' + e }); }
  }
})();
"""

