#!/usr/bin/env python
"""frida_time_hook.py - 覆写时间/随机源，让未修改的二进制在指定时间下自己产出 flag。

宿主侧脚本（stdlib only；运行模式才 import frida）。
实战背景：snake.exe 用 time.time() 播种 srand——枚举候选 unix 时间 + frida hook
把时钟钉在候选值上，二进制自己算出正确答案。本脚本生成并运行对应 hook。

三类时间源（--source）：
  win    kernel32/kernelbase!GetSystemTimeAsFileTime + GetSystemTimePreciseAsFileTime
  linux  libc time / gettimeofday / clock_gettime（默认只覆写 CLOCK_REALTIME，
         --all-clocks 连 CLOCK_MONOTONIC 一起钉——可能影响 sleep/超时逻辑）
  java   java.lang.System.currentTimeMillis（attach 模式，Android 用 --device usb）

用法：
  # 只生成脚本（离线审计/手工投递）
  python frida_time_hook.py --source win --value 1700000000 --list
  # 单值运行：Windows 目标挂起式 spawn（hook 先于入口点生效，stdout 捕获）
  python frida_time_hook.py --source win --value 1700000000 --spawn ./snake.exe --selfcheck
  # 枚举候选时间：逐个 spawn，stdout 命中 --pattern（默认 flag{...}）即停
  python frida_time_hook.py --source win --enumerate 1699990000:1700001000 \
      --spawn ./snake.exe --pattern "KEY=\\d+"
  # attach 到运行中进程（linux/java 的主路径）
  python frida_time_hook.py --source java --value 1700000000 --attach com.app --device usb

--value 接受："1700000000"（unix 秒）/ "unix:1700000000" / "filetime:133444736000000000"；
裸整数 >= 1e15 自动按 FILETIME 换算成 unix 秒。FILETIME = (unix+11644473600)*10^7。

frida 17 差异（实测 17.18.0）：
  - Device 无 output()：spawn 的 piped stdio 读不到 → Windows spawn 走
    CreateProcessW(CREATE_SUSPENDED) + 匿名管道捕获（attach 后 ResumeThread）。
  - JS 侧 Module.getGlobalExportByName 取代 findGlobalExportByName；
    findExportByName(null, ...) 仍可用——生成的 JS 三层兜底。
  - 非 Windows 宿主 spawn 退回 device.spawn(stdio=inherit)：输出直接上屏，
    --pattern 匹配不可用（会 warning）。

exit codes: 0 ok / 1 用法或 IO 错误 / 2 闸门拦截（frida 缺失、目标不存在、
组合非法、平台不符）。输出一律 JSON。生成物落盘 --out（默认
~/.kimi-work/frida_time_hook/<ts>/），便于 ledger.py 引证。
"""
