def parse_time_value(text: str) -> int:
    """-> unix seconds. Accepts unix: / filetime: / ft: prefixes; bare int
    >= 1e15 is treated as FILETIME and converted."""
    t = text.strip().lower()
    for pre in ("filetime:", "ft:"):
        if t.startswith(pre):
            ft = int(t[len(pre):], 0)
            return ft // 10_000_000 - FILETIME_EPOCH_DELTA
    if t.startswith("unix:"):
        return int(t[5:], 0)
    v = int(t, 0)
    if v >= 10**15:
        return v // 10_000_000 - FILETIME_EPOCH_DELTA
    return v


def unix_to_filetime(unix: int) -> int:
    return (unix + FILETIME_EPOCH_DELTA) * 10_000_000


def parse_enumerate(spec: str) -> list[int]:
    """"S:E[:STEP]" -> inclusive unix-second list (each item parse_time_value)."""
    parts = spec.split(":")
    # unix:/filetime: prefixes break naive split; only plain ints allowed here
    if len(parts) not in (2, 3):
        raise ValueError("--enumerate 需要 START:END[:STEP]（纯整数 unix 秒）")
    start, end = int(parts[0], 0), int(parts[1], 0)
    step = int(parts[2], 0) if len(parts) == 3 else 1
    if step == 0 or (end - start) * step < 0:
        raise ValueError("--enumerate 步长与区间方向不符")
    out, v = [], start
    while (v <= end if step > 0 else v >= end):
        out.append(v)
        v += step
    if not out:
        raise ValueError("--enumerate 区间为空")
    return out


def build_script(source: str, unix: int, selfcheck: bool = False,
                 all_clocks: bool = False) -> str:
    ft = unix_to_filetime(unix)
    repl = {
        "__UNIX__": str(unix),
        "__FT_LO__": str(ft & 0xFFFFFFFF),
        "__FT_HI__": str((ft >> 32) & 0xFFFFFFFF),
        "__MS__": str(unix * 1000),
        "__SELFCHECK__": "1" if selfcheck else "0",
        "__ALL_CLOCKS__": "1" if all_clocks else "0",
    }
    tmpl = {"win": WIN_JS, "linux": LINUX_JS, "java": JAVA_JS}[source]
    js = tmpl
    for k, v in repl.items():
        js = js.replace(k, v)
    leftover = re.findall(r"__[A-Z][A-Z0-9_]*__", js)
    if leftover:
        raise RuntimeError(f"模板替换残留: {sorted(set(leftover))}")
    return js


def emit(obj: dict) -> None:
    print(json.dumps(obj, ensure_ascii=False))


