class WinSpawn:
    def __init__(self):
        self.pid = 0
        self.h_process = None
        self.h_thread = None
        self._k32 = None
        self._out_chunks: list[bytes] = []
        self._err_chunks: list[bytes] = []
        self._readers: list[threading.Thread] = []

    def resume(self) -> None:
        self._k32.ResumeThread(self.h_thread)

    def wait(self, timeout_s: float) -> int:
        """-> exit code, or None on timeout (process killed)."""
        k32 = self._k32
        r = k32.WaitForSingleObject(self.h_process, int(timeout_s * 1000))
        if r == 0x00000102:  # WAIT_TIMEOUT
            k32.TerminateProcess(self.h_process, 0xFFFF)
            k32.WaitForSingleObject(self.h_process, 5000)
            return None
        code = ctypes.wintypes.DWORD()
        k32.GetExitCodeProcess(self.h_process, ctypes.byref(code))
        return code.value

    def drain(self, timeout_s: float = 5.0) -> tuple[str, str]:
        for t in self._readers:
            t.join(timeout_s)
        dec = lambda b: b.decode("utf-8", errors="replace")
        return dec(b"".join(self._out_chunks)), dec(b"".join(self._err_chunks))

    def close(self) -> None:
        k32 = self._k32
        for h in (self.h_thread, self.h_process):
            if h:
                k32.CloseHandle(h)


def _spawn_suspended_win32(exe: str, argv: list[str]) -> WinSpawn:
    import msvcrt
    from ctypes import wintypes as wt

    k32 = ctypes.WinDLL("kernel32", use_last_error=True)
    CREATE_SUSPENDED = 0x00000004
    STARTF_USESTDHANDLES = 0x00000100
    HANDLE_FLAG_INHERIT = 0x00000001
    STD_INPUT_HANDLE = -10 & 0xFFFFFFFF

    class SECURITY_ATTRIBUTES(ctypes.Structure):
        _fields_ = [("nLength", wt.DWORD), ("lpSecurityDescriptor", wt.LPVOID),
                    ("bInheritHandle", wt.BOOL)]

    class STARTUPINFOW(ctypes.Structure):
        _fields_ = [("cb", wt.DWORD), ("lpReserved", wt.LPWSTR), ("lpDesktop", wt.LPWSTR),
                    ("lpTitle", wt.LPWSTR), ("dwX", wt.DWORD), ("dwY", wt.DWORD),
                    ("dwXSize", wt.DWORD), ("dwYSize", wt.DWORD),
                    ("dwXCountChars", wt.DWORD), ("dwYCountChars", wt.DWORD),
                    ("dwFillAttribute", wt.DWORD), ("dwFlags", wt.DWORD),
                    ("wShowWindow", wt.WORD), ("cbReserved2", wt.WORD),
                    ("lpReserved2", wt.LPVOID),
                    ("hStdInput", wt.HANDLE), ("hStdOutput", wt.HANDLE),
                    ("hStdError", wt.HANDLE)]

    class PROCESS_INFORMATION(ctypes.Structure):
        _fields_ = [("hProcess", wt.HANDLE), ("hThread", wt.HANDLE),
                    ("dwProcessId", wt.DWORD), ("dwThreadId", wt.DWORD)]

    def make_pipe():
        r, w = wt.HANDLE(), wt.HANDLE()
        sa = SECURITY_ATTRIBUTES(ctypes.sizeof(SECURITY_ATTRIBUTES), None, True)
        if not k32.CreatePipe(ctypes.byref(r), ctypes.byref(w), ctypes.byref(sa), 0):
            raise OSError(ctypes.get_last_error(), "CreatePipe failed")
        k32.SetHandleInformation(r, HANDLE_FLAG_INHERIT, 0)
        return r, w

    r_out, w_out = make_pipe()
    r_err, w_err = make_pipe()

    si = STARTUPINFOW()
    si.cb = ctypes.sizeof(STARTUPINFOW)
    si.dwFlags = STARTF_USESTDHANDLES
    si.hStdInput = k32.GetStdHandle(STD_INPUT_HANDLE)
    si.hStdOutput = w_out
    si.hStdError = w_err
    pi = PROCESS_INFORMATION()

    cmdline = " ".join([f'"{exe}"'] + [a if re.fullmatch(r"[A-Za-z0-9_./:\\-]+", a)
                                       else f'"{a}"' for a in argv])
    ok = k32.CreateProcessW(None, cmdline, None, None, True, CREATE_SUSPENDED,
                            None, None, ctypes.byref(si), ctypes.byref(pi))
    k32.CloseHandle(w_out)
    k32.CloseHandle(w_err)
    if not ok:
        err = ctypes.get_last_error()
        raise OSError(err, f"CreateProcessW failed: {cmdline} (winerror {err})")

    sp = WinSpawn()
    sp.pid = pi.dwProcessId
    sp.h_process = pi.hProcess
    sp.h_thread = pi.hThread
    sp._k32 = k32

    def reader(handle, chunks):
        fd = msvcrt.open_osfhandle(handle, os.O_RDONLY)
        try:
            while True:
                data = os.read(fd, 65536)
                if not data:
                    break
                chunks.append(data)
        except OSError:
            pass
        finally:
            os.close(fd)

    for handle, chunks in ((r_out.value, sp._out_chunks), (r_err.value, sp._err_chunks)):
        t = threading.Thread(target=reader, args=(handle, chunks), daemon=True)
        t.start()
        sp._readers.append(t)
    return sp


